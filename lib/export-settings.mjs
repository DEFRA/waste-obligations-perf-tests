import { chmod, writeFile } from 'node:fs/promises'

const names = [
  'EPR_BASE_URL', 'EPR_CSO_USER_EMAIL', 'EPR_CSO_USER_PASSWORD', 'EPR_ORG_ID',
  'EPR_USER_EMAIL', 'EPR_USER_PASSWORD', 'LOAD_TEST_ACCEPT_PERCENTAGE',
  'LOAD_TEST_CSO_PERCENTAGE', 'LOAD_TEST_DURATION_MS', 'LOAD_TEST_JOURNEY_CONCURRENCY',
  'LOAD_TEST_JOURNEY_RATE_PER_MINUTE', 'LOAD_TEST_ORGANISATION_GROWTH_INTERVAL_SECONDS',
  'LOAD_TEST_RATE_PER_MINUTE', 'LOAD_TEST_USER_COUNT', 'LOAD_TEST_USER_ITERATIONS',
  'LOAD_TEST_USER_START_JITTER_MS', 'WASTE_OBLIGATION_CSO_ORG_ID',
  'WASTE_OBLIGATION_PASSWORD', 'WASTE_OBLIGATION_SUBMITTER_EMAIL',
  'WASTE_OBLIGATION_SUBMITTER_ID', 'WASTE_OBLIGATION_USERNAME'
]

const settings = Object.fromEntries(names.map(name => [name, process.env[name] ?? null]))
await writeFile(process.argv[2], `${JSON.stringify(settings, null, 2)}\n`, { mode: 0o600 })
await chmod(process.argv[2], 0o600)
